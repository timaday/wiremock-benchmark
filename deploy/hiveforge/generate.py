"""Derive the HiveForge lab template from the canonical GHCR Swarm stack.

Responsibility: project the stack and select active mocks for the swarm-lab profile.
Must not: deploy, discover hosts, read credentials, or redefine images/resources.
Contract: docs/HIVEFORGE.md and the HiveForge 0.5 Ansible action contract.
"""
from pathlib import Path
import re
import yaml

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / 'portainer/stack-ghcr.yml'
TARGET = ROOT / 'components/stack/ansible/templates/compose.yml.j2'
VARIABLE = re.compile(r'\$\{([A-Z][A-Z0-9_]*)(?::([?-])([^}]*))?\}')
# Public fixture credentials are intentional for this development lab.
LAB_CREDENTIAL = 'benchmark'
INPUTS = {'LAB_NODE': '{{ lab_node }}', 'CAPTURE_PREFIX': '{{ capture_prefix }}',
          'CAPTURE_ENABLED': '{{ capture_enabled }}'}


def template(source):
    def replace(match):
        name, operator, value = match.groups()
        if name in INPUTS:
            return INPUTS[name]
        if name in {'RABBIT_PASSWORD', 'GRAFANA_PASSWORD'}:
            return LAB_CREDENTIAL
        if operator == '-':
            return value
        raise ValueError(f'Undeclared HiveForge lab input: {name}')

    def resolve(value):
        if isinstance(value, str):
            return VARIABLE.sub(replace, value)
        if isinstance(value, list):
            return [resolve(item) for item in value]
        if isinstance(value, dict):
            return {key: resolve(item) for key, item in value.items()}
        return value

    stack = resolve(yaml.safe_load(source))
    replicas = {
        runtime: '{{ 1 if active_runtime in ["both", "' + runtime + '"] else 0 }}'
        for runtime in ('official', 'headless')
    }
    for runtime, expression in replicas.items():
        stack['services'][runtime]['deploy']['replicas'] = expression
    for service in stack['services'].values():
        for port in service.get('ports', []):
            if isinstance(port, dict):
                port['published'] = int(port['published'])
    rendered = yaml.safe_dump(stack, sort_keys=False)
    # Replica counts must render as YAML integers, not quoted strings.
    for expression in replicas.values():
        rendered = rendered.replace("'" + expression + "'", expression)
    if '${' in rendered:
        raise ValueError('Unresolved Compose interpolation in HiveForge template')
    return '# Generated by deploy/hiveforge/generate.py from the canonical GHCR stack.\n' + rendered


if __name__ == '__main__':
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(template(SOURCE.read_text()))
