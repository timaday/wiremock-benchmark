panel('Server duration p95 / p99 (includes delay)', [f'histogram_quantile({q}, sum by (runtime, le) (rate(wiremock_http_duration_seconds_bucket{selector}[$__rate_interval])))' for q in [.95,.99]], 's', ['{{runtime}} p95','{{runtime}} p99'])
