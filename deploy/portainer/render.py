def deploy(cpu, memory, restart='none'):
    return {'replicas': 1, 'placement': {'constraints': ['node.hostname == ${LAB_NODE:?set Swarm node hostname}']},
            'resources': {'limits': {'cpus': str(cpu), 'memory': memory}},
            'restart_policy': {'condition': restart}}

def service(image, cpu, memory, **settings):
    return {'image': f'{PREFIX}-{image}:{TAG}', 'deploy': deploy(cpu, memory), **settings}

