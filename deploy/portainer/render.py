def panel(title, expressions, unit, legends=None):
    i = len(panels)
    targets = [{'refId': chr(65+j), 'expr': expr, 'legendFormat': (legends[j] if legends else '{{runtime}}'), 'datasource': source} for j,expr in enumerate(expressions)]
    panels.append({'id': i+1, 'type': 'timeseries', 'title': title, 'datasource': source,
        'gridPos': {'x': ((i-1)%2)*12, 'y': 4+((i-1)//2)*8, 'w': 12, 'h': 8}, 'targets': targets,
        'fieldConfig': {'defaults': {'unit': unit, 'min': 0, 'custom': {'lineWidth': 2, 'fillOpacity': 8}}, 'overrides': []},
        'options': {'legend': {'displayMode': 'table', 'placement': 'bottom', 'calcs': ['lastNotNull']}}})
